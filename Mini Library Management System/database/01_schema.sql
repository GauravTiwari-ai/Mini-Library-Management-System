CREATE TABLE books (
    book_id              NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title                VARCHAR2(200) NOT NULL,
    author               VARCHAR2(150) NOT NULL,
    category             VARCHAR2(80) NOT NULL,
    price                NUMBER(10, 2) DEFAULT 0 NOT NULL,
    total_copies         NUMBER(6) NOT NULL,
    available_copies     NUMBER(6) NOT NULL,
    low_stock_threshold  NUMBER(6) DEFAULT 2 NOT NULL,
    CONSTRAINT books_price_ck CHECK (price >= 0),
    CONSTRAINT books_total_ck CHECK (total_copies >= 0),
    CONSTRAINT books_available_ck CHECK (
        available_copies >= 0 AND available_copies <= total_copies
    ),
    CONSTRAINT books_threshold_ck CHECK (low_stock_threshold >= 0)
);

CREATE TABLE members (
    member_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name   VARCHAR2(150) NOT NULL,
    email       VARCHAR2(254) NOT NULL,
    phone       VARCHAR2(30),
    join_date   DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    status      VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT members_email_uq UNIQUE (email),
    CONSTRAINT members_status_ck CHECK (status IN ('ACTIVE', 'INACTIVE'))
);

CREATE TABLE book_issues (
    issue_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id     NUMBER NOT NULL,
    member_id   NUMBER NOT NULL,
    issue_date  DATE DEFAULT TRUNC(SYSDATE) NOT NULL,
    due_date    DATE NOT NULL,
    return_date DATE,
    status      VARCHAR2(12) DEFAULT 'ACTIVE' NOT NULL,
    fine_amount NUMBER(10, 2) DEFAULT 0 NOT NULL,
    CONSTRAINT book_issues_book_fk FOREIGN KEY (book_id) REFERENCES books (book_id),
    CONSTRAINT book_issues_member_fk FOREIGN KEY (member_id) REFERENCES members (member_id),
    CONSTRAINT book_issues_status_ck CHECK (status IN ('ACTIVE', 'RETURNED')),
    CONSTRAINT book_issues_fine_ck CHECK (fine_amount >= 0),
    CONSTRAINT book_issues_dates_ck CHECK (due_date >= issue_date),
    CONSTRAINT book_issues_return_ck CHECK (
        (status = 'ACTIVE' AND return_date IS NULL) OR
        (status = 'RETURNED' AND return_date IS NOT NULL)
    )
);

CREATE TABLE audit_log (
    audit_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    issue_id    NUMBER NOT NULL,
    action_name VARCHAR2(12) NOT NULL,
    action_time TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    details     VARCHAR2(1000),
    CONSTRAINT audit_log_issue_fk FOREIGN KEY (issue_id) REFERENCES book_issues (issue_id),
    CONSTRAINT audit_log_action_ck CHECK (action_name IN ('ISSUE', 'RETURN'))
);

CREATE INDEX book_issues_status_due_ix ON book_issues (status, due_date);
CREATE INDEX book_issues_member_book_ix ON book_issues (member_id, book_id, status);
CREATE INDEX audit_log_action_time_ix ON audit_log (action_time);
